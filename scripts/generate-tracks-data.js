/* Builds site/tracks-data.js from content/tracks/*.md and quizzes/tracks/*.json.
   Run from the repo root:  node scripts/generate-tracks-data.js
   The output adds the track lessons to window.AIW_CONTENT / window.AIW_QUIZZES, which
   content-data.js and quiz-data.js create first (they are loaded before it in site/index.html). */

"use strict";

var fs = require("fs");
var path = require("path");

var root = path.join(__dirname, "..");
var contentDir = path.join(root, "content", "tracks");
var quizDir = path.join(root, "quizzes", "tracks");
var outFile = path.join(root, "site", "tracks-data.js");

// Source quizzes tend to put the right answer in the same slot. Reorder options with a
// permutation seeded by the question id, so the output is stable between runs and EN/FR stay aligned.
function shuffleOptions(q) {
  var seed = 2166136261; // FNV-1a, so near-identical ids still get unrelated seeds
  for (var c = 0; c < q.id.length; c++) seed = Math.imul(seed ^ q.id.charCodeAt(c), 16777619) >>> 0;
  function rand() { // mulberry32
    seed = (seed + 0x6D2B79F5) >>> 0;
    var t = Math.imul(seed ^ (seed >>> 15), seed | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  }
  var order = q.options_en.map(function (_, i) { return i; });
  for (var i = order.length - 1; i > 0; i--) {
    var j = Math.floor(rand() * (i + 1));
    var tmp = order[i]; order[i] = order[j]; order[j] = tmp;
  }
  q.options_en = order.map(function (k) { return q.options_en[k]; });
  q.options_fr = order.map(function (k) { return q.options_fr[k]; });
  q.answer_index = order.indexOf(q.answer_index);
}

var content = {};
fs.readdirSync(contentDir).filter(function (f) { return /\.md$/.test(f); }).sort().forEach(function (f) {
  content[f.replace(/\.md$/, "")] = fs.readFileSync(path.join(contentDir, f), "utf8").replace(/\r\n/g, "\n");
});

var quizzes = {};
fs.readdirSync(quizDir).filter(function (f) { return /\.json$/.test(f); }).sort().forEach(function (f) {
  var data = JSON.parse(fs.readFileSync(path.join(quizDir, f), "utf8"));
  Object.keys(data).forEach(function (id) {
    data[id].forEach(function (q, i) {
      ["question_en", "question_fr", "options_en", "options_fr", "explanation_en", "explanation_fr"].forEach(function (k) {
        if (!q[k]) throw new Error(f + " " + id + " question " + (i + 1) + " is missing " + k);
      });
      if (q.options_en.length !== q.options_fr.length) throw new Error(f + " " + id + " q" + (i + 1) + ": EN/FR option counts differ");
      if (!(q.answer_index >= 0 && q.answer_index < q.options_en.length)) throw new Error(f + " " + id + " q" + (i + 1) + ": bad answer_index");
      shuffleOptions(q);
    });
    quizzes[id] = data[id];
  });
});

Object.keys(quizzes).forEach(function (id) {
  if (!content[id]) throw new Error("Quiz " + id + " has no matching content/tracks/" + id + ".md");
});

var out = "// Auto-generated by scripts/generate-tracks-data.js — do not edit by hand.\n" +
  "// Edit content/tracks/*.md and quizzes/tracks/*.json, then re-run the script.\n" +
  "(function () {\n" +
  "  var content = " + JSON.stringify(content, null, 2).replace(/\n/g, "\n  ") + ";\n" +
  "  var quizzes = " + JSON.stringify(quizzes, null, 2).replace(/\n/g, "\n  ") + ";\n" +
  "  window.AIW_CONTENT = window.AIW_CONTENT || {};\n" +
  "  window.AIW_QUIZZES = window.AIW_QUIZZES || {};\n" +
  "  Object.keys(content).forEach(function (k) { window.AIW_CONTENT[k] = content[k]; });\n" +
  "  Object.keys(quizzes).forEach(function (k) { window.AIW_QUIZZES[k] = quizzes[k]; });\n" +
  "})();\n";

fs.writeFileSync(outFile, out, "utf8");
console.log("Wrote " + path.relative(root, outFile) + ": " + Object.keys(content).length + " pages, " +
  Object.keys(quizzes).length + " quizzes.");
